def build() -> Path:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    steps_html: list[str] = []
    plan_rows: list[str] = []

    for step in STEPS:
        shot = SHOTS / step["shot"]
        if not shot.exists():
            print(f"  ! нет кадра {step['shot']} — шаг «{step['title']}» пропущен")
            continue
        # Ссылка относительная: HTML лежит рядом, в docs/pdf.
        src = f"../story/{step['shot']}"
        looks = "".join(f"<li>{html.escape(x)}</li>" for x in step.get("look", []))
        say = html.escape(step["say"]).replace("**", "")
        steps_html.append(f"""
<section class="step">
  <div class="num">{html.escape(step["num"])}</div>
  <h2>{html.escape(step["title"])}<span class="role">{html.escape(step["role"])}</span></h2>
  <div class="say"><span class="label">Говорим</span>{say}</div>
  <figure><img src="{src}" alt=""></figure>
  <div class="look"><span class="label">На что смотреть</span><ul>{looks}</ul></div>
</section>""")
        plan_rows.append(
            f'<div><span>{html.escape(step["num"])}</span>'
            f'<span>{html.escape(step["title"])}</span></div>'
        )

    doc = f"""<!doctype html>
<html lang="ru"><head><meta charset="utf-8">
<title>Avito AI Reviewer — рассказ на защите</title>
<style>{CSS}</style></head>
<body>
<section class="cover">
  <div class="kicker">Хакатон Avito · кейс «AI Reviewer»</div>
  <h1>Рассказ на защите</h1>
  <div class="sub">Восемь минут показа: что говорим и что в этот момент на экране.
  Все кадры сняты с работающего приложения, не нарисованы.</div>
  <div class="plan">{"".join(plan_rows)}</div>
</section>
{"".join(steps_html)}
{CLOSING_HTML}
</body></html>"""

    path = OUT_DIR / "story.html"
    path.write_text(doc, encoding="utf-8")
    return path


