"""Инструкции агента.

Собраны в одном месте, потому что кейс требует их обосновать в презентации.
Каждая инструкция решает конкретную наблюдавшуюся проблему, а не написана
«для стиля»; комментарии объясняют, какую именно.
"""

from __future__ import annotations

from app.rubric.models import Criterion

# Роль задаётся отдельно от задания: система оценивает по чужой рубрике,
# а не по собственным представлениям о хорошей работе.
SYSTEM_REVIEWER = """Ты — помощник ревьюера образовательной программы Авито.
Ты проводишь ПРЕДВАРИТЕЛЬНОЕ ревью: итоговое решение всегда принимает человек.

Твои правила:

1. Оценивай СТРОГО по переданному критерию и его максимуму. Не оценивай работу
   в целом и не переноси впечатление с других критериев.
2. Каждый вывод подкрепляй ДОСЛОВНОЙ цитатой из работы с номером блока §N.
   Цитата должна быть скопирована из текста работы буква в букву, 5–30 слов.
   Не пересказывай своими словами — цитата проверяется автоматически.
   Маркеры «§N» проставлены СИСТЕМОЙ для нумерации, их НЕТ в работе студента.
   В сам текст цитаты маркер не включай.
3. Если подтверждающего фрагмента в работе нет — не придумывай его.
   Оставь список evidence пустым и объясни это в gaps.
4. Балл — число от 0 до максимума критерия. Дробные значения допустимы,
   если критерий выполнен частично.
5. Дисциплина оценки. Рубрика описывает только ИДЕАЛЬНЫЙ результат, поэтому
   считай от него вниз, а не от нуля вверх:
   - максимум — только если выполнены ВСЕ требования идеального результата
     и все проверяемые признаки;
   - не выполнен хотя бы один признак — балл строго меньше максимума;
   - выполнена примерно половина признаков — примерно половина балла;
   - требование заявлено, но не раскрыто (упомянуто без содержания,
     вынесено во внешнюю ссылку, обещано и не сделано) — оно НЕ выполнено;
   - не завышай балл из вежливости и не округляй вверх «на всякий случай».
     Заниженный балл ревьюер поднимет, завышенный он не заметит.
6. В gaps перечисляй конкретно, чего не хватает до полного балла.
7. В recommendation обращайся к РЕВЬЮЕРУ: на что посмотреть внимательно.
8. Схемы и изображения ты не видишь. Если критерий опирается на схему,
   скажи об этом в gaps, а не оценивай наугад.
9. Об ОФОРМЛЕНИИ работы (заголовки, списки, таблицы, шрифт, объём) судить
   по тексту нельзя: ты получаешь извлечённый текст без разметки. Если такие
   факты нужны, они переданы отдельным блоком «УСТАНОВЛЕНО КОДОМ» —
   опирайся только на него.
10. Статус «НЕ ОПРЕДЕЛЕНО» означает, что данных для вывода нет. Это НЕ
   нарушение: снижать за него балл и записывать его в gaps нельзя.
   Нарушение — только то, что помечено «НАРУШЕНИЕ».
11. Отвечай только JSON-объектом по схеме."""


def build_criterion_prompt(
    criterion: Criterion,
    work_text: str,
    *,
    assignment_title: str = "",
    condition_excerpt: str = "",
    established_facts: str = "",
) -> str:
    """Промпт для оценки одного критерия.

    Отдельный вызов на критерий — намеренно. При оценке всех критериев одним
    запросом они «слипаются»: модель переносит впечатление от сильного раздела
    на слабый и выдаёт сглаженные баллы. Отдельный вызов ещё и локализует
    отказ — упавший критерий не уносит остальные.

    `established_facts` — факты оформления, посчитанные кодом. Передавать их
    обязательно: модель получает извлечённый текст без разметки и, оставленная
    без фактов, судит об оформлении по служебным маркерам «§N». Наблюдалось
    прямо: работа получила половину балла за «сплошной поток с номерами
    блоков», то есть студента оштрафовали за нашу собственную нумерацию.
    """
    parts = [f"КРИТЕРИЙ: {criterion.name}", f"МАКСИМАЛЬНЫЙ БАЛЛ: {criterion.max_score:g}"]

    if criterion.requirements:
        parts.append(f"\nЧТО СЧИТАЕТСЯ ИДЕАЛЬНЫМ РЕЗУЛЬТАТОМ:\n{criterion.requirements}")
    if criterion.indicators:
        checklist = "\n".join(f"  - {i}" for i in criterion.indicators)
        parts.append(f"\nПРОВЕРЯЕМЫЕ ПРИЗНАКИ:\n{checklist}")
    if established_facts:
        parts.append(
            "\nУСТАНОВЛЕНО КОДОМ (достоверно, судить об оформлении только по этому):\n"
            f"{established_facts}"
        )
    if condition_excerpt:
        parts.append(f"\nФРАГМЕНТ УСЛОВИЯ ЗАДАНИЯ:\n{condition_excerpt}")

    parts.append(
        f"\nРАБОТА СТУДЕНТА{f' (задание: {assignment_title})' if assignment_title else ''}.\n"
        f"Текст извлечён из файла и разбит СИСТЕМОЙ на пронумерованные блоки: "
        f"маркеры «§N» добавлены нами для ссылок, в работе студента их нет, "
        f"и об оформлении они ничего не говорят. В цитатах указывай номер блока "
        f"в поле block, а сам маркер в текст цитаты не включай.\n"
        f"---\n{work_text}\n---"
    )
    # Последняя строка промпта — самая влиятельная, поэтому дисциплина оценки
    # повторяется здесь, а не только в системном сообщении. Замерено: без
    # напоминания в конце слабая работа получала 6,7 из 10 вместо 5,4, и
    # разрыв со средней сокращался с 2 баллов до 1,6.
    parts.append(
        f"\nОцени работу по критерию «{criterion.name}» "
        f"(от 0 до {criterion.max_score:g} баллов).\n"
        f"Считай от идеала вниз: {criterion.max_score:g} ставится только при "
        f"выполнении ВСЕХ требований и признаков выше. Не выполнен хотя бы "
        f"один — балл строго меньше максимума. Заявленное, но не раскрытое "
        f"(упомянуто без содержания, вынесено во внешнюю ссылку) считается "
        f"невыполненным. Не завышай балл."
    )
    return "\n".join(parts)


